export function translate(text, language, values = {}) {
  const template = language === 'en' && Object.hasOwn(english, text) ? english[text] : text
  return template.replace(/\{(\w+)\}/g, (match, key) => Object.hasOwn(values, key) ? String(values[key]) : match)
}
